package dev.phonebridge.core.plugins

import java.io.File
import kotlin.system.exitProcess

/**
 * The table of bundled plugins in `plugins/README.md`, generated from the plugin files so it never goes stale:
 * `./gradlew :core:pluginTable` (wrapped by `scripts/plugin-table.sh`) rewrites it, and [PluginTableTest] fails
 * `:core:test` (and so CI) when it is out of date.
 */
object PluginTable {
    const val START = "<!-- plugin-table:start (generated by scripts/plugin-table.sh from plugins/*/plugin.yaml; do not edit by hand) -->"
    const val END = "<!-- plugin-table:end -->"

    /** Why `plugins/README.md` can't be updated, or what to do when it is stale. */
    const val HOW_TO_UPDATE = "run ./scripts/plugin-table.sh to update it"

    /** The Markdown table for [plugins] (sorted by name), with links relative to `plugins/README.md`. */
    fun table(plugins: List<AppPlugin>): String {
        val rows = plugins.sortedWith(compareBy(String.CASE_INSENSITIVE_ORDER) { it.name }).map { p ->
            val actions = p.actions
            listOf(
                "[${cell(p.name)}](${p.id}/plugin.yaml)",
                p.androidPackages.joinToString("<br>") { "`$it`" }.ifEmpty { "-" },
                p.category,
                p.status.id + if (p.tested.isNotEmpty()) " (tested)" else "",
                "${actions.size}: " + cell(actions.joinToString(", ") { it.title }),
            ).joinToString(" | ", prefix = "| ", postfix = " |")
        }
        return buildString {
            append("| App | Android package | Category | Status | Actions |\n")
            append("|---|---|---|---|---|\n")
            if (rows.isEmpty()) append("| No bundled plugins yet | | | | |\n")
            rows.forEach { append(it).append('\n') }
        }
    }

    /**
     * [readme] with the text between [START] and [END] replaced by [table].
     * @throws IllegalArgumentException if the markers are missing or out of order.
     */
    fun update(readme: String, table: String): String {
        val start = readme.indexOf(START)
        val end = readme.indexOf(END)
        require(start >= 0 && end > start) { "plugins/README.md must contain the lines $START and $END" }
        return readme.substring(0, start + START.length) + "\n" + table + readme.substring(end)
    }

    /** The valid plugins of [pluginsDir] (folders starting with `_` left out), or the problems of the others. */
    fun load(pluginsDir: File): PluginCatalogLoad {
        val files = pluginsDir.listFiles { f -> f.isDirectory && !f.name.startsWith("_") && !f.name.startsWith(".") }.orEmpty()
            .mapNotNull { dir -> File(dir, "plugin.yaml").takeIf { it.isFile }?.let { PluginFile("plugins/${dir.name}/plugin.yaml", it.readText()) } }
        return PluginCatalog.load(files, runExamples = false)
    }

    /** `plugins/README.md` as it should be. @throws IllegalStateException if a plugin can't be loaded. */
    fun expected(pluginsDir: File): String {
        val load = load(pluginsDir)
        check(load.errors.isEmpty()) { "Fix the plugins first (./scripts/plugin-check.sh):\n" + load.errors.joinToString("\n") }
        return update(File(pluginsDir, "README.md").readText(), table(load.catalog.plugins))
    }

    /** A Markdown table cell: no pipes or line breaks. */
    private fun cell(text: String): String = text.replace("|", "\\|").replace(Regex("\\s+"), " ").trim()
}

/** `pluginTable` entry point: args = [plugins dir] [--check]. With --check, exits 1 when the README is stale instead of writing it. */
fun main(args: Array<String>) {
    val dir = File(args.getOrNull(0) ?: "plugins")
    val check = "--check" in args
    val readme = File(dir, "README.md")
    val expected = try {
        PluginTable.expected(dir)
    } catch (e: Exception) {
        System.err.println(e.message)
        exitProcess(1)
    }
    when {
        readme.readText() == expected -> println("plugins/README.md is up to date.")
        check -> {
            System.err.println("plugins/README.md is out of date: ${PluginTable.HOW_TO_UPDATE}.")
            exitProcess(1)
        }
        else -> {
            readme.writeText(expected)
            println("Updated the plugin table in plugins/README.md.")
        }
    }
}
